def _sort(column: str, direction: str = "ascending", nulls: str = "last") -> dict[str, Any]:
    """Return one sort key.

    A constructor rather than a literal at each call site, so the resulting document carries a
    known element type. A bare ``[]`` inside a nested literal infers as ``list[Unknown]``, which
    strict type checking reports for every case that holds one.
    """
    return {"column": column, "direction": direction, "nulls": nulls}


def _sheet(source: str, partition_column: str | None, sort: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    """Return one sheet entry, with an empty sort by default."""
    keys: list[dict[str, Any]] = [] if sort is None else sort
    return {"source": source, "partition_column": partition_column, "sort": keys}


def _sheets(*entries: dict[str, Any]) -> list[dict[str, Any]]:
    """Return a typed list of sheet entries."""
    return list(entries)


def _date_column(column: dict[str, Any], *, alias: str = "sales", name: str = "transaction_date") -> dict[str, Any]:
    """Return the base document with one source's single date column replaced."""
    document: dict[str, Any] = copy.deepcopy(BASE)
    document["sources"][alias]["date_columns"] = {name: column}
    document["profiles"][0]["sheets"][0]["partition_column"] = name
    return document


def _balanced() -> dict[str, Any]:
    """Return the base document switched to balanced partitioning, with null partition columns."""
    document: dict[str, Any] = copy.deepcopy(BASE)
    document["profiles"][0]["partitioning"] = {"algorithm": "balanced", "balance_across": "worksheets"}
    sheet: dict[str, Any]
    for sheet in document["profiles"][0]["sheets"]:
        sheet["partition_column"] = None
    return document


def _drop(path: tuple[str | int, ...]) -> dict[str, Any]:
    """Return the base document with one key removed, addressed by a path of keys and indices."""
    document: dict[str, Any] = copy.deepcopy(BASE)
    cursor: Any = document
    step: str | int
    for step in path[:-1]:
        cursor = cursor[step]
    del cursor[path[-1]]
    return document


