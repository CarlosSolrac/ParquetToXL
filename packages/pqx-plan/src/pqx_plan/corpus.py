def as_records() -> list[dict[str, Any]]:
    """Return every case as a plain JSON-serialisable record.

    The form the exported artifact takes, and the form a validator written in another language
    can consume: no Python types, no dataclasses, one object per case.

    Returns:
        One record per case, in corpus order.
    """
    return [
        {
            "id": case.identifier,
            "reason": case.reason,
            "structurally_valid": case.structurally_valid,
            "semantic_only": case.semantic,
            "expected_findings": case.findings,
            "dialect_divergence": case.dialect_divergence,
            "document": case.document,
        }
        for case in ALL_CASES
    ]


ARTIFACT_HEADER: str = "Generated by tools/build_config_corpus.py. Do not edit by hand."
"""Stamped into the exported JSON so nobody edits the copy instead of the source."""


def render_artifact() -> str:
    """Return the exported artifact's exact text, newline-terminated.

    Lives here rather than in the tool so the test that guards the committed file can compare
    against it without importing from ``tools/``, which is not a package on a test's import path.

    Returns:
        Pretty-printed JSON, stable across runs so a diff shows only real changes.
    """
    return json.dumps({"$comment": ARTIFACT_HEADER, "cases": as_records()}, indent=2, ensure_ascii=False, sort_keys=False) + "\n"
