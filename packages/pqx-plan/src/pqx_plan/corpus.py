"""The shared corpus: configuration documents both validators must classify identically.

``export-pipeline-spec.md`` asks for this rather than for a generated-and-diffed comparison of
the JSON Schema against the Pydantic models. Diffing the two would test the *representation*, and
the two legitimately differ in spelling -- ``unevaluatedProperties`` against
``additionalProperties``, ``if``/``then`` against a ``model_validator``. What must agree is the
**verdict**, so the corpus is a set of documents each marked valid or invalid with the reason, and
the rule is that both sides say the same thing about every one.

Each case is a mutation of one valid base document, so a case describes exactly one difference and
a failure names it. ``structurally_valid`` is what the schema and the models must agree on;
semantic-only rules are marked ``structurally_valid=True`` with ``semantic=True``, because those
are deliberately outside the schema's reach and are checked against
:func:`pqx_plan.semantics.findings` instead.

**Why this ships in the package rather than living beside the tests.** ``export-pipeline-spec.md``
says the corpus doubles as the fixture set for the web configuration editor, which is a separate
tool in a different language. Keeping it importable means the exported
``docs/export-config-corpus.json`` can be regenerated by anyone who has this package, rather than
only from inside this repository's test session.
"""

